    /** One nationality in a language — Arabic, or English; empty for none (or an unknown code). */
    public static function name(?string $code, bool $arabic): string
    {
        $names = self::ALL[strtoupper((string) $code)] ?? null;

        return $names ? $names[$arabic ? 1 : 0] : '';
    }

    /**
     * To choose from: code => its name in the interface's language, in that language's order.
     *
     * @return array<string, string>
     */
    public static function options(): array
    {
        $arabic = app()->getLocale() === 'ar';
        $options = array_map(fn (array $names): string => $names[$arabic ? 1 : 0], self::ALL);
        asort($options, SORT_LOCALE_STRING);

        return $options;
    }
